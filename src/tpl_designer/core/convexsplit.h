#pragma once

// Невыпуклая область (с дырками) -> выпуклые многоугольники.
//
// 🔑 Зачем. Ядро заливает полигон под выражением ВЕЕРОМ треугольников от первой
// вершины (`SetPoly` в TmcRTHNodeDiel.cpp: узел внутри, если он в одном из
// треугольников p0, p[k-1], p[k]). Для невыпуклого многоугольника веер вылезает за
// контур и залезает в вырезы — среда молча выходит не та. Сечение линзы, подложки с
// окном, трубы — невыпуклое почти всегда. Поэтому область режется на выпуклые куски,
// и каждый идёт отдельным блоком.

#include <QPointF>
#include <QVector>

namespace tpl {

/// Разрезать область на выпуклые многоугольники.
///
/// \p loops — замкнутые контуры области; что внутри, решает чётно-нечётное правило
/// (контур внутри контура — дырка, в дырке — остров). Способ: вертикальные полосы
/// между соседними по x вершинами режут область на трапеции, соседние трапеции
/// сливаются, пока объединение выпукло. Вырождений у этого способа нет — ни дырки, ни
/// касания контуров его не ломают, в отличие от отсечения «ушей».
///
/// Возвращает многоугольники без повторов вершин; обход — против часовой стрелки
/// (порядок для ядра расставляет эмиттер).
QVector<QVector<QPointF>> convexPieces(const QVector<QVector<QPointF>> &loops);

/// Треугольник -> четырёхугольник с вершиной посередине стороны.
///
/// Заливной полигон, по справочнику языка (tpl-guide 5.4), должен иметь БОЛЬШЕ трёх
/// вершин, и проверка задания это требует. Точка на стороне геометрию не меняет, а
/// веер ядра от любой вершины выпуклого многоугольника покрывает его целиком.
/// Не треугольник возвращается как есть.
QVector<QPointF> padTriangle(const QVector<QPointF> &p);

/// Площадь многоугольника со знаком (против часовой — плюс).
double polyArea(const QVector<QPointF> &p);

} // namespace tpl
