#include "project.h"

#include <QString>

namespace tpl {

/// Сколько памяти уйдёт на расчёт — то, что можно сказать ДО прогона.
///
/// Числа взяты не из головы. Память на узел ЗАМЕРЕНА на сервере 30.09.2026
/// (`TMC_Suite/GPU_PLAN.md`, «Память на узел»): H — 52 байта на узел, X — 127 байт
/// на узел, это с блоками; голая область чуть дешевле (30 и 89). Берём «с блоками»:
/// задание без единой фигуры не считают.
///
/// Накопление для диаграммы направленности устроено так (`FieldIntegrated.cpp`
/// ДН-сборки ядра):
///  * одна частота — четыре массива по 8 байт на КАЖДЫЙ узел области (cos, sin,
///    амплитуда, фаза). Если они не влезают в четверть свободной памяти, ядро само
///    переходит на полосы вдоль контура — так что это оценка СВЕРХУ;
///  * несколько тонов (`#FREQ` в файле сигнала) — всегда полосы толщиной три узла по
///    четырём сторонам контура ДН, но по ПАРЕ квадратур на каждый тон. Память растёт
///    линейно с числом тонов.
struct RamEstimate {
    double nodes = 0.0;        ///< узлов сетки
    double gridBytes = 0.0;    ///< сама сетка: поля, проводимости, списки узлов блоков
    bool pattern = false;      ///< заказана ли диаграмма направленности
    int patternTones = 0;      ///< на скольких частотах копится ДН в одном прогоне (<= 99)
    int patternToneRequest = 0;///< сколько тонов назвал сигнал — до обрезки
    bool patternBorder = false;///< копится по полосам вдоль контура, а не по всей области
    double patternBytes = 0.0; ///< накопление ДН

    double total() const { return gridBytes + patternBytes; }
};

/// \p freeBytes — свободная память машины, где будут считать (0 — неизвестна).
///
/// Нужна для ДН одной частоты: ядро копит её по всей области, но переходит на полосы
/// вдоль контура, если четыре массива на всю сетку заняли бы больше четверти
/// свободной памяти (`SetBorderModeIfNeeded`, область меньше 32 узлов по стороне — всегда
/// по всей). Зная свободную память, повторяем это правило; не зная — считаем по всей
/// области, то есть оценка сверху.
RamEstimate ramEstimate(const Project &p, double freeBytes = 0.0);

/// Порог предупреждения: 2 ГиБ.
///
/// Граница не случайная. Это всё адресное пространство 32-разрядного процесса, а
/// пакет поставляется и 32-разрядными ядрами (`dist/win32`): выше они не выделят
/// память при любом объёме ОЗУ. И это же порог, за которым обычному ноутбуку уже
/// бывает тесно.
inline constexpr double kRamWarnBytes = 2.0 * 1024.0 * 1024.0 * 1024.0;

/// «1.4 ГБ», «380 МБ», «12 КБ» — для подписей и предупреждений.
QString formatBytes(double bytes);

} // namespace tpl
