/// Что нарисовано.
///
/// `Polyline` и `Polygon` — один и тот же примитив языка (`POLYGON_STAT`), но с разным
/// смыслом: у контурного материала последняя точка НЕ соединяется с первой, поэтому
/// ломаная — это просто линия, а замкнутый контур эмиттер закрывает сам, повторив
/// первую точку. Пользователю про это знать нечего: он рисует «линию» или «контур».
enum class ShapeKind { Rectangle, Circle, Polygon, Polyline };

/// Сторона прямоугольника. Порядок обхода — как рисует ядро: низ, право, верх, лево.
enum RectEdge { EdgeBottom = 0, EdgeRight = 1, EdgeTop = 2, EdgeLeft = 3 };

/// Одна сторона прямоугольного контура.
///
/// Ядро рисует `RECT_STAT METAL` целиком периметром — «убрать одну стенку» одним блоком
/// нельзя. Поэтому если стороны различаются, эмиттер разбирает прямоугольник на
/// отдельные ломаные-блоки. Для пользователя это остаётся одной фигурой.
struct EdgeSpec {
    bool present = true;                    ///< сторона существует (снятая = открытый торец)
    bool custom = false;                    ///< материал свой, а не общий для фигуры
    Material material = Material::Metal;    ///< действует только при custom
};

/// Фигура на сцене = один BLOCK в задании (или несколько, если стороны разные).
///
/// ⚠️ Координаты ЛОКАЛЬНЫЕ. К ним ядро прибавляет анкер (X0,Y0) из #LINK_LIST.
/// Для редактора это внутренняя кухня: пользователь двигает фигуру в абсолютных
/// координатах сцены, а как разложить их на «локальные + анкер» решает эмиттер.
/// Единственное место, где анкер вылезает наружу: у окружности центра в блоке нет
/// вообще — центром служит именно анкер.
struct Shape {
    int id = 0;      ///< номер BLOCK. Произвольный, требование только id >= 1 и уникальность
    QString name;    ///< для легенды слева; в файл уходит комментарием
    ShapeKind kind = ShapeKind::Rectangle;

    Material material = Material::Metal;
    double eps = 1.0; ///< если material == Dielectric. В файл уходит eps-1

    /// Неоднородная eps по формуле. Заменяет собой число `eps`, когда включена.
    EpsProfile epsProfile;

    /// Плазма поверх фигуры. Одна фигура = N и/или B и/или Y в одной области.
    Plasma plasma;

    // --- прямоугольник (абсолютные координаты сцены, мм) ---
    double xMin = 0.0, xMax = 0.0, yMin = 0.0, yMax = 0.0;

    /// Стороны прямоугольного контура: низ, право, верх, лево.
    std::array<EdgeSpec, 4> edges{};

    // --- окружность/сектор ---
    QPointF center;                 ///< уйдёт в анкер: в самом блоке центра нет
    double rMin = 0.0, rMax = 0.0;  ///< кольцо; rMin = 0 — сплошной круг
    double fiMin = 0.0, fiMax = 0.0;///< сектор, радианы; 0..2pi — полная окружность

    // --- полигон и ломаная (абсолютные координаты сцены, мм) ---
    QVector<QPointF> points;

    // --- движение (RECT_MOVE и т.п.); нулевая скорость = статичный блок ---
    double vx = 0.0, vy = 0.0;
    bool isMoving() const { return vx != 0.0 || vy != 0.0; }

    /// Рисуется ли фигура контуром (материал) или заливкой (выражение eps / плазма).
    bool isContour() const;

    /// Все четыре стороны на месте и одного материала — тогда хватит одного RECT_STAT.
    /// У заливки сторон не бывает вовсе: выражение задаёт площадь целиком.
    bool hasUniformEdges() const;

    /// Материал конкретной стороны с учётом переопределения.
    Material edgeMaterial(int edge) const;

    /// Концы стороны прямоугольника в координатах сцены.
    QPointF edgeFrom(int edge) const;
    QPointF edgeTo(int edge) const;

    /// Ограничивающий прямоугольник в координатах сцены — для вписывания вида и попаданий.
    void bounds(double *xLo, double *xHi, double *yLo, double *yHi) const;

    /// Задана ли eps формулой. Только это отличает `RECT_STAT` с числом от `RECT_STAT`
    /// с выражением — для языка разницы нет, для пользователя есть.
    bool hasEpsProfile() const;

    /// Начало отсчёта координат в формуле eps: центр прямоугольника.
    ///
    /// Это не украшение, а способ обойти ловушку. Ядро подставляет в выражение
    /// координаты ОТНОСИТЕЛЬНО анкера блока (`SetYLineForDiel` вычитает dX0, dY0),
    /// поэтому, поставив анкер в центр, получаем формулы вида `exp(-r^2/w^2)` без
    /// поправок на положение фигуры на сцене — и они не ломаются при её переносе.
    QPointF epsOrigin() const;
};

/// Знаковая площадь ломаной. > 0 — обход против часовой стрелки (ось Y вверх).
/// Нужна эмиттеру: заливному полигону ядро требует обход ПО часовой.
double signedArea(const QVector<QPointF> &pts);

/// Выпуклый ли контур. Ядро выпуклость не проверяет — ошибка вылезет неверным полем.
bool isConvex(const QVector<QPointF> &pts);

