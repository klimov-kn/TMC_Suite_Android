/// Конвейер заданий: одну сетку частот разложить по НЕСКОЛЬКИМ файлам задания.
///
/// Зачем. Свип «от 1 до 100 ГГц» — это тысяча частот, и в одно задание они не
/// лезут: в один файл `.s` пакет укладывает не больше 99 точек
/// (`FREQ_MAX_NUM = 100`, отказ в `libs/SFILE95/Unite_s.cpp:68`). Раньше на каждую
/// частоту писали свой файл руками, а потом сшивали результат скриптом.
///
/// Здесь то же самое делается делением: «частот в одном задании = 10» превращает
/// 1000 частот в 100 заданий `<имя>_001.tpl` ... `<имя>_100.tpl`, каждое со своим
/// `.s`, плюс пакетный файл, который прогоняет их по очереди.
///
/// 🔑 Широкополосный сигнал из файла конвейер НЕ заменяет и не отменяет. Один проход
/// на всю полосу быстрее в число частот, но в плазме он не годится: X-ядро считает
/// плазменную добавку один раз, из `FREQ` (`PlanarRT_X/TmcRTHRectNode.cpp:1122`), то
/// есть среда «заморожена» на частоте согласования. Для плазмы от 1 до 100 ГГц
/// единственный верный путь — именно пачка заданий.
struct Chunking {
    bool enabled = false;
    /// Сколько частот кладём в одно задание. Любое число, а не только 10.
    int freqsPerTask = 10;
};

/// Вариант расчёта: та же геометрия, но часть фигур выключена.
///
/// Каждый `#STEP` в языке самодостаточен — у него своя топология. Значит пустой
/// волновод и он же с диэлектриком считаются ОДНИМ заданием за ОДИН прогон, а не
/// двумя файлами, которые надо править руками.
struct Variant {
    QString name;              ///< «пустой», «с диэлектриком» — уйдёт в комментарий
    QString tag;               ///< короткая добавка к именам файлов: wg, di
    QVector<int> disabledShapes; ///< номера фигур, выключенных в этом варианте

    bool isEnabled(int shapeId) const { return !disabledShapes.contains(shapeId); }
};

/// Угловой свип: объект поворачивается от шага к шагу, источник стоит на месте.
///
/// Так считают рассеяние под разными углами (моностатическую ЭПР): плоская волна
/// приходит всегда с одной стороны, а тело на каждом шаге повёрнуто на следующий угол.
/// Повернуть сам источник язык не позволяет — входов всего два вида, `INPUT_X` и
/// `INPUT_Y`, то есть волна идёт только вдоль осей, а `Faza` зависит лишь от `t` и `f`,
/// наклонного фронта не собрать. Для рассеяния важен только угол «волна — тело», так
/// что поворот тела физически равен повороту источника.
///
/// Устроен как частотный свип: шаг описан ОДИН раз макросом с углом в параметре, число
/// шагов равно числу строк вызова. Координаты повёрнутых фигур ядро считает само —
/// `L <выражение>; <выражение>;` с `cos`/`sin` оно принимает (проверено прогоном
/// 2026-09-23).
///
/// ⚠️ Точка `.s` пишется ПОД УГЛОМ: второй параметр `SMATRIX` — только подпись точки,
/// частоту счёта он не меняет (проверено прогоном: подписи 30 и 45 дали ровно то же, что
/// FREQ). Но подпись 0 ядро теряет — точка в файл не попадает вовсе. Поэтому угол 0°
/// подписывается как 360° (см. \ref sweepLabel).
struct AngleSweep {
    bool enabled = false;
    QVector<int> shapeIds;     ///< какие фигуры поворачиваются — это и есть «объект»
    /// Ось — в центре объекта (габарита поворачиваемых фигур) и ездит вместе с ним.
    ///
    /// Так по умолчанию: пользователь двигает объект по холсту, и ось обязана идти
    /// следом. Раньше ось хранилась числом, и после переноса фигуры поворот шёл вокруг
    /// старого места — объект «улетал» из коробки (замечание пользователя 2026-09-23).
    bool pivotAtCenter = true;
    QPointF pivot;             ///< ось поворота, мм — только при pivotAtCenter == false
    QVector<double> angles;    ///< углы поворота, градусы, против часовой стрелки
    /// Первым шагом посчитать ту же сцену БЕЗ объекта. Отклик пустой области нужен,
    /// чтобы вычесть его из откликов с объектом: иначе к рассеянию подмешиваются
    /// отражения от поглотителей и от самого входа.
    bool referenceStep = true;

    bool active() const { return enabled && !shapeIds.isEmpty() && !angles.isEmpty(); }
    bool rotates(int shapeId) const { return active() && shapeIds.contains(shapeId); }
};

/// Ось поворота, которой пользуются эмиттер, проверка и холст: центр габарита
/// поворачиваемых фигур (при pivotAtCenter) или заданная точка.
QPointF sweepPivot(const struct Project &p);

/// Подпись точки `.s` для угла: угол, приведённый в (0; 360]. Ноль ядро теряет.
double sweepLabel(double angleDeg);

/// Добавка к имени файла сигналов для угла: `a30`, `a12p5`, `am15` (минус). Точку в имени
/// ядро приняло бы за расширение.
QString sweepFileTag(double angleDeg);

/// Добавка к имени файла сигналов для частоты: `f3p9`, `f10`, `f0p5`.
///
/// Нужна, потому что имя файла сигналов у шага ОДНО, а шагов в свипе много: без
/// метки каждый следующий шаг переписывал бы `.t` предыдущего, и от всего свипа
/// оставался бы сигнал последней частоты. С матрицей `.s` этого не видно — она
/// дописывается, — а для широкополосной постобработки и для взгляда на сигнал во
/// времени `.t` каждого шага и есть результат. Так же названы файлы в авторских
/// заданиях (`wg_s30.t` ... `wg_s48.t`).
QString freqFileTag(double ghz);

/// Поворот точки на угол (градусы) вокруг оси.
QPointF rotatePoint(const QPointF &p, const QPointF &pivot, double angleDeg);

/// Фигура после поворота. Прямоугольник становится контуром или заливным полигоном:
/// повёрнутый прямоугольник языку не выразить. Для показа и проверок — в файл идёт
/// то же самое, только выражениями.
struct Shape rotatedShape(const struct Shape &s, const QPointF &pivot, double angleDeg);

/// Всё задание целиком — то, что мастер собирает по шагам.
struct Project {
    QString name; ///< имя файла .tpl без расширения
    QString description;

    Kernel kernel = Kernel::H;
    LengthUnit unit = LengthUnit::Millimeter; ///< единица ввода; в файл всегда мм

    Box box;
    double delta = 1.0;     ///< шаг сетки, мм
    double timeMax = 115.0; ///< конец счёта, нс

    QVector<double> freqs; ///< ГГц. Одна — обычный .tpl, больше — макро-версия

    QVector<Shape> shapes;
    QVector<Port> ports;
    OutputSettings output;

    /// Варианты геометрии. Пусто — один вариант «как нарисовано».
    QVector<Variant> variants;

    /// Порты, возбуждаемые ПО ОЧЕРЕДИ: на каждый — свой `#STEP`.
    ///
    /// Возбуждение порта j даёт СТОЛБЕЦ матрицы (S1j, S2j, ...). Перечислив здесь оба
    /// порта, получаем полную матрицу 2x2 за один прогон: шаги дописывают строки
    /// в общий `.s` (проверено побайтно 2026-08-04).
    /// Пусто — один шаг с портами, помеченными активными вручную.
    QVector<int> exciters;

    /// Поворот объекта по шагам (ЭПР). Несовместим с вариантами и очередью
    /// возбуждений: точка `.s` подписывается углом, и развести по файлам разные
    /// устройства или столбцы матрицы было бы нечем.
    AngleSweep sweep;

    /// Разложить сетку частот по нескольким файлам задания.
    Chunking chunking;

    /// Свободный номер блока: у портов и фигур общее пространство номеров.
    int nextFreeId() const;

    QVector<Port> activePorts() const;

    /// Номер порта «для человека»: 1, 2, 3... по порядку в списке.
    int portOrdinal(int id) const;

    /// Сколько шагов `#STEP` получится: варианты x возбуждения x частоты, а при
    /// угловом свипе — опорный шаг плюс по шагу на угол.
    int stepCount() const;

    /// На сколько файлов задания разложится сетка частот. Без конвейера — 1.
    int chunkCount() const;
};

