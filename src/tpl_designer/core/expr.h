#pragma once

#include <QHash>
#include <QString>
#include <QStringList>
#include <QVector>

#include <optional>

namespace tpl {

struct ExprCompiler;

/// Единица измерения аргументов тригонометрии — это `ANGLE_UNIT` из `#PARM`.
///
/// ⚠️ Ядро применяет её к аргументам sin/cos/tan и к результату asin/acos/atan
/// (`Expr/EXPR_COM.CPP`), поэтому вычислять выражение из файла, не зная единицы,
/// нельзя: `sin(90)` — это либо 0.894, либо 1.0.
enum class AngleUnit { Radian, Gradus };

/// Вычисляет числовое выражение входного языка `.tpl`.
///
/// Понимает то же, что интерпретатор ядра (tpl-guide 9.1):
///   + - * / ^, круглые скобки, унарный минус, числа вида 3.1e+17;
///   abs exp log log10 sqrt sin cos tan asin acos atan sinh cosh tanh.
///
/// Возвращает `nullopt`, если выражение не число: содержит имя переменной
/// (`x`, `y`, `r`, `f`, `t`), нераскрытый макрос или синтаксическую ошибку.
/// Это НЕ повод падать — вызывающий обязан положить предупреждение и жить дальше.
///
/// ⚠️ Приоритет операций здесь общепринятый (степень > умножение/деление >
/// сложение/вычитание). Авторское руководство 2000 года описывает другой порядок
/// («деление перед умножением»), поэтому во всех авторских заданиях скобки
/// расставлены явно — и расхождение никого не задевает.
std::optional<double> evalExpression(const QString &text, AngleUnit angle = AngleUnit::Radian);

/// Значения переменных выражения.
///
/// Ядро подставляет их ТЕКСТОМ перед разбором: `CalcEps` печатает
/// `x=(...);y=(...);r=(...);f=(...);` и скармливает интерпретатору отдельной строкой
/// (`kernels/PlanarRT_H/TmcRTHNodeDiel.cpp:1608`). Поэтому набор имён задаёт
/// вызывающий, а не парсер: в разных контекстах он разный.
using Variables = QHash<QString, double>;

/// То же вычисление, но с известными значениями переменных.
///
/// ⚠️ Имена берутся из контекста ядра и НЕ совпадают между собой:
/// в выражении eps `f` — это ПОЛЯРНЫЙ УГОЛ (atan2(y,x)), а в выражениях Amp/Faza
/// порта `f` — ЧАСТОТА в ГГц. Одна буква, две разные величины; путать нельзя.
std::optional<double> evalExpression(const QString &text, const Variables &vars,
                                     AngleUnit angle = AngleUnit::Radian);

/// Переменные, которые ядро подставляет в выражение eps для точки (x, y).
///
/// Координаты — в единицах `LONG_UNIT` и ОТНОСИТЕЛЬНО анкера блока: `SetYLineForDiel`
/// вычитает (dX0, dY0) прежде чем звать `CalcEps`. Угол — в единицах `ANGLE_UNIT`.
Variables epsVariables(double x, double y, AngleUnit angle = AngleUnit::Radian);

/// Встречается ли в выражении голое имя, которого нет среди известных переменных.
///
/// Нужно, чтобы отличить «формула ссылается на частоту через макро-параметр» от
/// «формула зависит только от координат»: первое делает файл `.eps` пригодным ровно
/// для одной частоты, второе — для всего свипа.
QStringList unknownNames(const QString &text, const Variables &known);

/// Похоже ли на имя материала (METAL/MAGNETIC/ABSORBER), а не на выражение.
bool isMaterialKeyword(const QString &text);

/// Переписывает выражение под другую единицу длины.
///
/// Координаты `x`, `y` и радиус `r` ядро подставляет в единицах `LONG_UNIT` того
/// файла, где выражение написано. Модель редактора всегда в миллиметрах, и файл он
/// пишет тоже в миллиметрах, — значит формулу из файла в сантиметрах нужно
/// пересчитать, иначе профиль растянется в десять раз. Каждое вхождение имени
/// заменяется на `(имя*factor)`; `factor` — во сколько раз новая единица меньше
/// старой (для «см -> мм» это 0.1).
///
/// Заменяются только ЦЕЛЫЕ имена: `x` внутри `exp(` не имя, а часть другого слова,
/// и числа вида `3.1e+17` тоже не трогаются.
QString scaleCoordinates(const QString &text, double factor);

/// Один раз разобранное выражение, которое потом считают тысячи раз.
///
/// Зачем отдельный тип. `evalExpression` разбирает строку заново на КАЖДЫЙ вызов, и
/// это незаметно, пока вызовов единицы. Профиль eps рисуется по сетке 192x192 на
/// фигуру: на задании с полусотней профилей выходит несколько миллионов разборов
/// строки в 250 символов — окно замирало на 15-20 секунд. Разбор здесь делается один
/// раз, дальше считается готовое дерево.
///
/// Арифметика сишная, как в ядре: деление на ноль и переполнение дают бесконечность,
/// `sqrt` отрицательного — NaN. Отвергается только ИТОГ, если он оказался нечислом.
/// Промежуточная бесконечность законна: `1/exp(1000)` — это ноль, а не ошибка.
class ExprProgram
{
    friend struct ExprCompiler;

public:
    ExprProgram() = default;

    /// Разбирает выражение. Неразобранная программа не считается вовсе.
    static ExprProgram compile(const QString &text, AngleUnit angle = AngleUnit::Radian);

    bool valid() const { return m_ok; }

    /// Голые имена в порядке первой встречи: `x`, `y`, `r`, `f` и всё прочее.
    const QStringList &names() const { return m_names; }

    /// Есть ли имя, которого нет среди переданных. Пустой список — выражение число.
    QStringList unknown(const Variables &known) const;

    /// Считает с произвольным набором переменных (медленный путь: поиск по имени).
    std::optional<double> eval(const Variables &vars) const;

    /// Профиль eps в точке (x, y). Быстрый путь: слоты переменных найдены при разборе,
    /// поиска по имени нет. Если в выражении есть имя помимо `x y r f` — `nullopt`.
    std::optional<double> evalEps(double x, double y) const;

private:
    /// Узел дерева. Ссылки — индексы в `m_nodes`, а не указатели: так дерево лежит
    /// одним куском памяти и копируется тривиально.
    struct Node {
        int op = 0;       ///< код операции, таблица в expr.cpp
        int a = -1, b = -1;
        int idx = -1;     ///< слот переменной либо номер функции
        double num = 0.0; ///< значение константы
    };

    double run(int i, const double *vals, bool *bad) const;

    QVector<Node> m_nodes;
    QStringList m_names;
    int m_root = -1;
    int m_slotX = -1, m_slotY = -1, m_slotR = -1, m_slotF = -1;
    bool m_foreignName = false; ///< встретилось имя помимо x, y, r, f
    bool m_ok = false;
    AngleUnit m_angle = AngleUnit::Radian;
};

} // namespace tpl
